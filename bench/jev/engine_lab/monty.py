"""Actual Azdaja staged handoff. Only a fixed binary and /usr/bin/false provider.

No native judge external function is added. Programs are supplied explicitly by
the experiment author, not generated by a model in this laboratory.
"""
from pathlib import Path
import re
import tempfile

from ..adapter import canonical_bytes, strict_json_loads
from ..bridge import _private_write, _run


EMIT = '''generation += 1
manifest = {"version": 1, "session": context["session"], "generation": generation,
            "source_sha256": sha256(source), "contracts": context["contracts"], "jobs": jobs}
manifest_text = json.dumps(manifest)
FINAL(manifest_text)
'''

# Only publish bound answers after every row has passed. A failed exec poisons
# the host Session, so no caller can silently keep using a previous stage.
BIND = '''incoming = json.loads(incoming_raw)
trusted = json.loads(binding_raw)
assert incoming["stage_ticket"] == trusted["stage_ticket"], "stage ticket mismatch"
assert incoming["version"] == 1 and incoming["complete"] == True, "incomplete stage"
assert incoming["session"] == context["session"], "session mismatch"
assert incoming["generation"] == generation, "generation mismatch"
assert incoming["source_sha256"] == sha256(source), "source mismatch"
assert incoming["manifest_sha256"] == sha256(manifest_text), "manifest mismatch"
assert trusted["session"] == context["session"], "trusted session mismatch"
assert trusted["generation"] == generation, "trusted generation mismatch"
assert trusted["source_sha256"] == sha256(source), "trusted source mismatch"
assert trusted["manifest_sha256"] == sha256(manifest_text), "trusted manifest mismatch"
expected_jobs = {}
for job in manifest["jobs"]:
    assert job["id"] not in expected_jobs, "duplicate request"
    expected_jobs[job["id"]] = job
checked = {}
for row in incoming["rows"]:
    rid = row["id"]
    assert rid in expected_jobs and rid not in checked, "unexpected or duplicate response"
    job = expected_jobs[rid]
    request = json.loads(job["request_json"])
    assert row["request_sha256"] == sha256(job["request_json"]), "request mismatch"
    assert row["profile"] == request["profile"], "profile mismatch"
    assert row["contract_sha256"] == context["contracts"][request["profile"]], "contract mismatch"
    assert rid in trusted["observations"], "unregistered observation"
    observation = trusted["observations"][rid]
    assert observation["request_sha256"] == row["request_sha256"], "observation request mismatch"
    assert observation["contract_sha256"] == row["contract_sha256"], "observation contract mismatch"
    assert observation["response_sha256"] == sha256(row["response_json"]), "response observation mismatch"
    body = json.loads(row["response_json"])
    assert len(body["answers"]) == len(request["questions"]), "answer coverage"
    for qid in request["questions"]:
        assert qid in body["answers"], "missing answer"
    checked[rid] = body["answers"]
assert len(checked) == len(expected_jobs), "missing response"
assert len(checked) == len(trusted["observations"]), "observation coverage"
bound = checked
FINAL({"bound": len(bound), "generation": generation})
'''


class Session:
    def __init__(self, binary, scratch, source, contracts):
        self.binary = Path(binary).resolve(strict=True)
        scratch = Path(scratch)
        scratch.mkdir(parents=True, exist_ok=True)
        self.tmp = tempfile.TemporaryDirectory(prefix="jev-engine-", dir=scratch)
        self.root = Path(self.tmp.name)
        self.home = self.root / "home"
        self.home.mkdir(mode=0o700)
        self.config = self.root / "config.toml"
        self.sid = None
        self.stopped = False
        self.loads = 0
        _private_write(self.config, "sub_llm_cmd = '/usr/bin/false'\ndefault_model = 'offline-engine'\n"
                       "output_cap = 262144\ncell_timeout = 10\nmax_calls_per_cell = 1\n"
                       "max_depth = 1\nmax_sessions = 1\nclean_patterns = []\n")
        try:
            self.sid = self._call(["start"]).strip()
            if not re.fullmatch(r"[A-Za-z0-9_-]{1,128}", self.sid):
                raise ValueError("invalid session")
            self.load("source", canonical_bytes(source).decode())
            self.load("context_raw", canonical_bytes({"session": self.sid, "contracts": contracts}).decode())
            self.execute('context = json.loads(context_raw)\nrecords = json.loads(source)\ngeneration = 0\n')
        except BaseException:
            self.close()
            raise

    def _call(self, args, stdin=""):
        try:
            result = _run(self.binary, args, self.home, self.config, stdin)
        except BaseException:
            self.stopped = True
            raise
        if result.returncode != 0:
            self.stopped = True
            # Synthetic input only. Preserve evaluator diagnostics for falsification.
            message = (result.stdout + result.stderr).decode("utf-8", errors="replace")[-1800:]
            raise ValueError("offline evaluator rejected: " + message)
        return result.stdout.decode("utf-8")

    def load(self, name, text):
        if self.stopped:
            raise ValueError("session stopped")
        try:
            if (not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z_]{0,40}", name)
                    or not isinstance(text, str) or len(text.encode()) > 262144):
                raise ValueError("invalid load")
            self.loads += 1
            path = self.root / f"input-{self.loads}.json"
            _private_write(path, text)
            self._call(["load", self.sid, str(path), name])
        except BaseException:
            self.stopped = True
            raise

    def execute(self, code):
        if self.stopped:
            raise ValueError("session stopped")
        self._call(["exec", self.sid], code)

    def final(self):
        if self.stopped:
            raise ValueError("session stopped")
        return self._call(["final", self.sid]).rstrip("\n")

    def plan(self, code):
        self.execute(code + "\n" + EMIT)
        return self.final()

    def bind(self, engine, result):
        try:
            # A mutable view may reorder rows, but cannot rewrite a recorded
            # observation. The authority is retained by the trusted host engine.
            binding = engine.trusted_binding(result["stage_ticket"])
            self.load("binding_raw", canonical_bytes(binding).decode())
            self.load("incoming_raw", canonical_bytes(result).decode())
            self.execute(BIND)
            return strict_json_loads(self.final())
        except BaseException:
            self.stopped = True
            raise

    def value(self, code):
        self.execute(code)
        return strict_json_loads(self.final())

    def close(self):
        try:
            if self.sid and re.fullmatch(r"[A-Za-z0-9_-]{1,128}", self.sid):
                self._call(["kill", self.sid])
        finally:
            self.tmp.cleanup()
            self.sid = None

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()
